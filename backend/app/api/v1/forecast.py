def _load_observations(db: Session, commodity_id: str, geography_id: str) -> List[Dict[str, Any]]:
    obs = db.query(MarketObservation).filter(
        MarketObservation.commodity_id == commodity_id,
        MarketObservation.geography_id == geography_id,
    ).order_by(MarketObservation.date.asc()).all()
    return [{
        "date": o.date,
        "min_price": o.min_price,
        "modal_price": o.modal_price,
        "max_price": o.max_price,
        "arrivals_mt": o.arrivals_mt,
    } for o in obs]


def _predict_with_champion_or_fallback(
    df: pd.DataFrame, horizon: int
) -> Dict[str, Any]:
    """
    Runs real Chronos-2; falls back to the Ridge AR-Lag model only if the
    foundation model can't load — and labels the fallback honestly.
    """
    try:
        adapter = Chronos2FoundationModel()
        points = adapter.predict(df, horizon)
        return {
            "points": points,
            "model_name": "Amazon Chronos-2 (pretrained, zero-shot)",
            "model_version": "chronos-2 / apache-2.0",
            "status": "CHRONOS2_REAL",
        }
    except ChronosUnavailableError as exc:
        model = AutoregressiveCovariateModel()
        points = model.predict(df, horizon)
        return {
            "points": points,
            "model_name": "AR-Lag Tabular (Ridge) — FALLBACK: Chronos-2 unavailable",
            "model_version": "v1-tabular-fallback",
            "status": "ARLAG_FALLBACK",
            "fallback_reason": str(exc),
        }


def _sanitize_for_json(obj):
    """Replace NaN/inf floats with None before JSON serialization."""
    import math
    if isinstance(obj, dict):
        return {k: _sanitize_for_json(v) for k, v in obj.items()}
    if isinstance(obj, list):
        return [_sanitize_for_json(v) for v in obj]
    if isinstance(obj, float) and (math.isnan(obj) or math.isinf(obj)):
        return None
    return obj


def _load_backtest_metrics(geography_id: str, horizon_days: int) -> Optional[Dict[str, Any]]:
    """Returns real backtest metrics for the nearest evaluated horizon bucket."""
    if not os.path.exists(METRICS_STORE_PATH):
        return None
    try:
        with open(METRICS_STORE_PATH, "r", encoding="utf-8") as fh:
            store = json.load(fh)
    except (OSError, json.JSONDecodeError):
        return None

    geo_block = store.get("by_geography", {}).get(geography_id) or store.get("by_geography", {}).get("default")
    if not geo_block:
        return None

    buckets = sorted((int(k) for k in geo_block.keys()))
    if not buckets:
        return None
    bucket = min(buckets, key=lambda b: (b > horizon_days, abs(b - horizon_days))) \
        if horizon_days else buckets[-1]
    # choose the largest bucket <= horizon, else the smallest bucket
    eligible = [b for b in buckets if b <= horizon_days]
    bucket = max(eligible) if eligible else buckets[0]

    metrics_block = geo_block.get(str(bucket), {})
    champion = next((m for m in metrics_block.get("models", []) if m.get("is_champion")), None)
    if champion is None:
        return None
    return {
        "backtest_horizon_days": bucket,
        "model_name": champion["model_name"],
        "mae": champion["mae"],
        "rmse": champion["rmse"],
        "wape_pct": champion["wape_pct"],
        # legacy-UI compatibility aliases (same real values, old key names)
        "wape": champion["wape_pct"],
        "interval_coverage": champion.get("interval_80_coverage_pct"),
        "interval_80_coverage_pct": champion.get("interval_80_coverage_pct"),
        "interval_95_coverage_pct": champion.get("interval_95_coverage_pct"),
        "eval_samples": champion.get("eval_samples"),
        "backtest_generated_at": store.get("generated_at"),
    }


def _dynamic_advisory(
    horizon_days: int,
    latest_modal: float,
    modal_30d_ago: Optional[float],
    points: List[Dict[str, Any]],
) -> str:
    """Advisory text computed from actual forecast numbers — no templates."""
    alert = settings.ONION_ALERT_THRESHOLD
    crisis = settings.ONION_CRISIS_THRESHOLD
    risk = probability_sheet(points, alert=alert, crisis=crisis)
    alert30 = risk.get("alert_exceedance", {}).get("day30", 0.0)
    crisis30 = risk.get("crisis_exceedance", {}).get("day30", 0.0)
    day30_val = points[min(30, len(points)) - 1]["predicted_modal"] if points else latest_modal

    trend_words = "stable"
    if modal_30d_ago:
        change_pct = (latest_modal - modal_30d_ago) / modal_30d_ago * 100.0
        trend_words = f"{'up' if change_pct > 1 else 'down' if change_pct < -1 else 'stable'} ({change_pct:+.1f}% over 30 days)"

    if alert30 >= 0.5:
        stance = (
            f"Alert threshold ₹{alert}/kg has >50% exceedance probability by day 30; "
            "buffer-release and procurement triggers under the Stabilisation Framework apply."
        )
    elif alert30 >= 0.2:
        stance = "Elevated breach risk — monitor arrivals and keep buffer-release optionality open."
    else:
        stance = "No intervention trigger under threshold rules; continue routine monitoring."

    return (
        f"{horizon_days}-Day Outlook: AP modal projected ₹{day30_val:.2f}/kg by day 30 "
        f"(latest ₹{latest_modal:.2f}/kg, trend {trend_words}). "
        f"Exceedance probability — alert ₹{alert}/kg: {alert30*100:.0f}%, "
        f"crisis ₹{crisis}/kg: {crisis30*100:.0f}%. {stance} "
        f"Probabilities derived from the Chronos-2 forecast distribution (quantile ladder)."
    )



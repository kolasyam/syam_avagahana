@router.get("/latest")
def get_latest_forecast(
    commodity_id: str = Query("onion"),
    geography_id: str = Query(settings.PILOT_MARKET_ID),
    horizon_days: int = Query(14, ge=7, le=90),
    refresh: bool = Query(False, description="Recompute even if a cached run exists"),
    db: Session = Depends(get_db),
):
    # 1. Serve the most recent cached real-model run for instant demo responses
    if not refresh:
        cached = db.query(ForecastRun).filter(
            ForecastRun.commodity_id == commodity_id,
            ForecastRun.geography_id == geography_id,
            ForecastRun.horizon_days == horizon_days,
            ForecastRun.status == "CHRONOS2_REAL",
        ).order_by(ForecastRun.run_date.desc(), ForecastRun.id.desc()).first()
        if cached is not None:
            points = json.loads(cached.forecast_series_json)
            metrics = json.loads(cached.metrics_json) if cached.metrics_json else None
            # A metrics blob that is only a placeholder note is NOT metrics —
            # fall back to the real rolling-backtest artifact.
            if metrics is not None and not isinstance(metrics, dict):
                metrics = None
            if isinstance(metrics, dict) and "wape_pct" not in metrics and "mae" not in metrics:
                metrics = None
            if metrics is None:
                metrics = _load_backtest_metrics(geography_id, horizon_days)
            # dynamic risk + advisory also on the fast cached path
            latest_modal = points[-1].get("predicted_modal") if points else None
            modal_30d_ago = None
            prev = db.query(MarketObservation).filter(
                MarketObservation.commodity_id == commodity_id,
                MarketObservation.geography_id == geography_id,
                MarketObservation.date <= cached.data_cutoff_date,
                MarketObservation.date >= (pd.Timestamp(cached.data_cutoff_date) - pd.Timedelta(days=35)).strftime("%Y-%m-%d"),
            ).order_by(MarketObservation.date.asc()).first()
            if prev is not None:
                modal_30d_ago = prev.modal_price
            cutoff_dt = pd.Timestamp(cached.data_cutoff_date)
            obs_recent = db.query(MarketObservation).filter(
                MarketObservation.commodity_id == commodity_id,
                MarketObservation.geography_id == geography_id,
                MarketObservation.date <= cached.data_cutoff_date,
                MarketObservation.date >= (cutoff_dt - pd.Timedelta(days=35)).strftime("%Y-%m-%d"),
            ).order_by(MarketObservation.date.desc()).first()
            if obs_recent is not None:
                latest_modal = obs_recent.modal_price
            return {
                "id": cached.id,
                "commodity_id": cached.commodity_id,
                "geography_id": cached.geography_id,
                "run_date": cached.run_date,
                "model_name": cached.model_name,
                "model_version": cached.model_version,
                "horizon_days": cached.horizon_days,
                "status": cached.status,
                "data_cutoff_date": cached.data_cutoff_date,
                "forecast_series": points,
                "metrics": metrics if metrics else _load_backtest_metrics(geography_id, horizon_days),
                "cached": True,
                "latest_modal_price": latest_modal,
                "risk_projection": probability_sheet(
                    points, alert=settings.ONION_ALERT_THRESHOLD, crisis=settings.ONION_CRISIS_THRESHOLD
                ),
                "advisory": _dynamic_advisory(horizon_days, latest_modal or 0, modal_30d_ago, points),
            }

    obs = _load_observations(db, commodity_id, geography_id)
    if not obs or len(obs) < 14:
        raise HTTPException(status_code=404, detail="Insufficient observation history for reliable forecast.")

    df = pd.DataFrame(obs)
    data_cutoff = obs[-1]["date"]

    # 30-day-ago modal for dynamic trend wording
    cutoff_dt = pd.to_datetime(data_cutoff)
    modal_30d_ago = None
    for o in reversed(obs):
        if (cutoff_dt - pd.to_datetime(o["date"])).days >= 30:
            modal_30d_ago = o["modal_price"]
            break
    latest_modal = obs[-1]["modal_price"]

    result = _predict_with_champion_or_fallback(df, horizon_days)
    points = result["points"]
    metrics = _load_backtest_metrics(geography_id, horizon_days)

    response = {
        "id": f"fc_{commodity_id}_{geography_id}_{horizon_days}d",
        "commodity_id": commodity_id,
        "geography_id": geography_id,
        "run_date": datetime.now(timezone.utc).strftime("%Y-%m-%d"),
        "model_name": result["model_name"],
        "model_version": result["model_version"],
        "horizon_days": horizon_days,
        "status": result.get("status", "COMPLETED"),
        "data_cutoff_date": data_cutoff,          # REAL cutoff from data
        "forecast_series": points,
        "metrics": metrics,                        # REAL backtest metrics or None
        "metrics_note": None if metrics else
            "Backtest metrics artifact not yet generated — run scripts/run_backtest.py. No invented accuracy values are shown.",
        "latest_modal_price": latest_modal,
        "risk_projection": probability_sheet(
            points, alert=settings.ONION_ALERT_THRESHOLD, crisis=settings.ONION_CRISIS_THRESHOLD
        ),
        "advisory": _dynamic_advisory(horizon_days, latest_modal, modal_30d_ago, points),
    }
    if "fallback_reason" in result:
        response["fallback_reason"] = result["fallback_reason"]
    return response


@router.post("/run")
def trigger_forecast_run(
    commodity_id: str = Query("onion"),
    geography_id: str = Query(settings.PILOT_MARKET_ID),
    horizon_days: int = Query(14, ge=7, le=90),
    db: Session = Depends(get_db),
):
    obs = _load_observations(db, commodity_id, geography_id)
    if len(obs) < 14:
        raise HTTPException(status_code=400, detail="Insufficient observation history for reliable forecast.")

    df = pd.DataFrame(obs)
    data_cutoff = obs[-1]["date"]

    result = _predict_with_champion_or_fallback(df, horizon_days)
    points = result["points"]
    metrics = _load_backtest_metrics(geography_id, horizon_days)

    run = ForecastRun(
        id=f"fc_{commodity_id}_{geography_id}_{datetime.now(timezone.utc).strftime('%Y%m%d%H%M%S')}_{datetime.now(timezone.utc).strftime('%f')[:3]}",
        commodity_id=commodity_id,
        geography_id=geography_id,
        run_date=datetime.now(timezone.utc).strftime("%Y-%m-%d"),
        model_name=result["model_name"],
        model_version=result["model_version"],
        horizon_days=horizon_days,
        forecast_series_json=json.dumps(_sanitize_for_json(points)),
        metrics_json=json.dumps(_sanitize_for_json(metrics)) if metrics else json.dumps({"note": "pending_backtest_artifact"}),
        data_cutoff_date=data_cutoff,
        status=result.get("status", "COMPLETED"),
    )
    db.add(run)
    db.commit()

    log_audit_event(
        db,
        actor_id="system",
        actor_role="ForecastAgent",
        action="FORECAST_RUN",
        target_type="ForecastRun",
        target_id=run.id,
        details={
            "model": result["model_name"],
            "geography": geography_id,
            "horizon_days": horizon_days,
            "data_cutoff": data_cutoff,
        },
    )

    return {
        "id": run.id,
        "commodity_id": run.commodity_id,
        "geography_id": run.geography_id,
        "run_date": run.run_date,
        "model_name": run.model_name,
        "model_version": run.model_version,
        "horizon_days": run.horizon_days,
        "status": run.status,
        "data_cutoff_date": run.data_cutoff_date,
        "forecast_series": points,
        "metrics": metrics,
        "risk_projection": probability_sheet(
            points, alert=settings.ONION_ALERT_THRESHOLD, crisis=settings.ONION_CRISIS_THRESHOLD
        ),
    }


@router.get("/backtest")
def get_backtest_report(
    commodity_id: str = Query("onion"),
    geography_id: str = Query(settings.PILOT_MARKET_ID),
    horizon_days: int = Query(14, ge=7, le=90),
    db: Session = Depends(get_db),
):
    """Returns the precomputed rolling-origin backtest artifact when available;
    otherwise computes it live (Chronos-2 folds may take a while on CPU)."""
    if os.path.exists(METRICS_STORE_PATH):
        try:
            with open(METRICS_STORE_PATH, "r", encoding="utf-8") as fh:
                store = json.load(fh)
            geo_block = store.get("by_geography", {}).get(geography_id) or store.get("by_geography", {}).get("default")
            if geo_block:
                response = dict(store)
                response["geography_id"] = geography_id
                response["horizon_requested"] = horizon_days
                return response
        except (OSError, json.JSONDecodeError):
            pass

    obs = _load_observations(db, commodity_id, geography_id)
    if len(obs) < 45:
        raise HTTPException(status_code=400, detail="Insufficient observation history for backtest.")

    report = evaluate_models_backtest(obs, horizon=min(horizon_days, 30))
    report["geography_id"] = geography_id
    report["horizon_requested"] = horizon_days
    return report

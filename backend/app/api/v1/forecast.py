"""
Forecasting and Backtesting API Endpoints
=========================================
Serves forecasts from the REAL pretrained Chronos-2 foundation model
(champion) with the Ridge AR-Lag tabular model as deterministic fallback.

Data honesty rules:
  - run_date / data_cutoff_date come from the ingested data, never hardcoded.
  - metrics come from the rolling-origin backtest artifact (forecast_metrics.json)
    generated by scripts/run_backtest.py — no invented accuracy numbers.
  - No synthetic long-horizon "easing" adjustments: Chronos-2 models the
    seasonality from 4+ years of real data itself.
"""

